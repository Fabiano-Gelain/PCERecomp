"""Annotated .asm listing from an Analysis.

For each ROM bank: code as instructions (with labels) and the rest as `.db`.
Marker column: `X` = executed instruction (confirmed by the coverage), `.` = deduced.
Labels: sub_BB_AAAA (called with JSR/BSR or interrupt entry) and loc_BB_AAAA
(jump/branch target), where BB = bank and AAAA = logical address.
"""


def label_name(point, kinds):
    prefix = "sub" if "sub" in kinds else "loc"
    for k in sorted(kinds):
        if k.startswith("vec_"):
            prefix = k
    return f"{prefix}_{point.bank:02X}_{(point.page << 13) | point.offset:04X}"


def write_listing(analysis, path, title="", functions=None):
    rom = analysis.rom
    by_bank = {}
    for info in analysis.code.values():
        by_bank.setdefault(info.point.bank, {}).setdefault(info.point.offset, info)

    names = {p: label_name(p, kinds) for p, kinds in analysis.labels.items() if p in analysis.code}
    st = analysis.stats()

    with open(path, "w", encoding="utf-8") as out:
        out.write(f"; {title}\n; Disassembly generated by tools/recomp (do not commit: derived from the ROM)\n")
        out.write(f"; CRC32 {rom.crc32:08X}, {rom.bank_count} banks\n")
        for k, v in st.items():
            out.write(f";   {k}: {len(v) if isinstance(v, list) else v}\n")
        out.write("; Column: X = executed (coverage), . = deduced\n")

        # ROM and, in CD games, the virtual banks of the disc loads (program.py)
        virtual = sorted(b for b in by_bank if b >= 0x100)
        for bank in list(range(rom.bank_count)) + virtual:
            code = by_bank.get(bank, {})
            pages = sorted({i.point.page for i in code.values()})
            origin = f" (seen on page {', '.join(str(p) for p in pages)})" if pages else " (no code found)"
            if bank >= 0x100:
                delta, real = rom.vinfo[bank]
                origin += f" = disc load in real bank {real:02X} (disc position = RAM + {delta:X})"
            out.write(f"\n; ======== bank {bank:02X}{origin} ========\n")
            data = [_byte(rom, bank, o) for o in range(0x2000)]
            off = 0
            while off < 0x2000:
                info = code.get(off)
                if info is not None:
                    p = info.point
                    if functions and p in functions:
                        f = functions[p]
                        tails = ""
                        if f.tail_calls:
                            tails = ", jumps to " + ", ".join(names.get(t, "?") for t in sorted(f.tail_calls))
                        out.write(f"\n; ---- function {names.get(p, '?')}: {len(f.body)} instructions{tails} ----\n")
                    if p in names:
                        out.write(f"{names[p]}:\n")
                    ins = info.ins
                    addr = (p.page << 13) | p.offset
                    hexbytes = " ".join(f"{b:02X}" for b in ins.bytes)
                    comment = ""
                    tg = sorted(analysis.targets.get(p, ()))
                    if tg:
                        comment = " ; -> " + ", ".join(names.get(t, f"{t.bank:02X}:{(t.page << 13) | t.offset:04X}") for t in tg)
                    out.write(f"  {'X' if info.executed else '.'} {addr:04X}  {hexbytes:20s}  {ins.text}{comment}\n")
                    off += ins.opcode.size
                    continue
                start = off
                while off < 0x2000 and off not in code and off - start < 16:
                    off += 1
                chunk = ", ".join("??" if b is None else f"${b:02X}" for b in data[start:off])
                out.write(f"         {start:04X}  .db {chunk}\n")


def _byte(rom, bank, offset):
    """Byte of the bank, or None if there is none (part of a virtual bank outside the load)."""
    try:
        return rom.read(bank, offset)
    except ValueError:
        return None
