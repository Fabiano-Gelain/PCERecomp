"""Merges BIOS profiles (pce_trace --bios-profile; runtime/pce/bios_profile.h) from several play sessions and
writes a Markdown report with the name of each routine (docs/hardware/systemcard/huc_system.inc).

Usage: python tools/recomp/bios_report.py [--title "BIOS routines used by <game>"] <output.md> <profile.txt> [...]
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
NAMES_FILE = os.path.join(ROOT, "docs", "hardware", "systemcard", "huc_system.inc")

# System Card 2.0 (US) vectors, read from $FFF6 in BIOS bank 0.
INTERRUPTS = {"E74F": "IRQ2 (CD-ROM / BRK)", "E889": "IRQ1 (VDC: VBlank and scanline)", "E6CC": "Timer",
              "E0F3": "Reset (startup)"}

GROUPS = [("cd_", "CD"), ("ad_", "ADPCM"), ("bm_", "Save memory"), ("ex_", "Video and system"),
          ("ma_", "Math"), ("psg_", "Chip music (PSG)"), ("grp_", "Graphics")]


def load_names():
    names = {}
    with open(NAMES_FILE, encoding="latin-1") as f:
        for line in f:
            m = re.match(r"\s*([a-z_0-9]+)\s*=\s*\$(E0[0-9A-Fa-f]{2})\b", line)
            if m:
                names.setdefault(m.group(2).upper(), m.group(1))
    return names


def parse(paths):
    routines = {}
    for path in paths:
        with open(path) as f:
            for line in f:
                if not line.startswith("R "):
                    continue
                parts = line.split()
                kind, addr = parts[1], parts[2]
                fields = dict(p.split("=", 1) for p in parts[3:])
                r = routines.setdefault((kind, addr), {"calls": 0, "instructions": 0, "ram": set(), "cdram": 0,
                                                      "bram": 0, "vdc": set(), "vce": 0, "psg": 0, "timer": 0,
                                                      "joypad": 0, "irq": 0, "cd": set(), "mpr": set(),
                                                      "sessions": 0})
                r["sessions"] += 1
                for k in ("calls", "instructions", "cdram", "bram", "vce", "psg", "timer", "joypad", "irq"):
                    r[k] += int(fields[k])
                for k in ("vdc", "cd", "mpr"):
                    if fields[k] != "-":
                        r[k] |= set(fields[k].split(","))
                if fields["ram"] != "-":
                    for part in fields["ram"].split(","):
                        lo, _, hi = part.partition("-")
                        r["ram"] |= set(range(int(lo, 16), int(hi or lo, 16) + 1))
    return routines


def ranges(addrs):
    out, s = [], sorted(addrs)
    i = 0
    while i < len(s):
        j = i
        while j + 1 < len(s) and s[j + 1] == s[j] + 1:
            j += 1
        out.append(f"${s[i]:04X}" + (f"-${s[j]:04X}" if j > i else ""))
        i = j + 1
    return ", ".join(out) if out else "—"


def main():
    if sys.argv[1:2] in (["-h"], ["--help"]):
        print(__doc__)
        return 0
    args = sys.argv[1:]
    title = "BIOS routines used by the game"
    if "--title" in args[:-1]:
        k = args.index("--title")
        title = args[k + 1]
        del args[k:k + 2]
    if len(args) < 2:
        print(__doc__)
        return 2
    out_path, paths = args[0], args[1:]
    names = load_names()
    routines = parse(paths)
    lines = [f"# {title}", "",
             f"Generated by `tools/recomp/bios_report.py` from {len(paths)} profile(s) of the user's play sessions",
             "(`pce_trace --bios-profile`, see `runtime/pce/bios_profile.h`). Addresses and counts only.", "",
             "Columns: BIOS calls and instructions executed (summed over the sessions); what the BIOS instructions",
             "wrote during the call (work RAM by address; CD RAM and save memory in bytes; VDC registers by",
             "number; VCE/PSG/timer/joypad/interrupts in writes; CD registers $18xx; MPR windows swapped).", ""]

    def row(key, r):
        kind, addr = key
        name = names.get(addr, INTERRUPTS.get(addr, "?")) if kind == "C" else INTERRUPTS.get(addr, "?")
        io = []
        for k, label in (("cdram", "CD RAM"), ("bram", "save"), ("vce", "VCE"), ("psg", "PSG"),
                         ("timer", "timer"), ("joypad", "joypad"), ("irq", "IRQ")):
            if r[k]:
                io.append(f"{label} {r[k]}")
        if r["vdc"]:
            io.append("VDC R" + ",".join(sorted(r["vdc"])))
        if r["cd"]:
            io.append("CD $18" + ",$18".join(sorted(r["cd"])))
        if r["mpr"]:
            io.append("MPR " + ",".join(sorted(r["mpr"])))
        return (f"| `${addr}` | {name} | {r['calls']} | {r['instructions']} | {ranges(r['ram'])} | "
                f"{'; '.join(io) or '—'} |")

    header = ["| Entry | Name | Calls | Instructions | RAM written | Hardware |", "|---|---|---|---|---|---|"]
    lines += ["## Startup and interrupts", ""] + header
    for key in sorted(routines):
        if key[0] in ("B", "I") or key[1] == "E0F3":
            if key[0] == "B" and routines[key]["instructions"] == 0:
                continue
            lines.append(row(key, routines[key]))
    calls = {k: v for k, v in routines.items() if k[0] == "C" and k[1] != "E0F3"}
    for prefix, title in GROUPS:
        group = [k for k in sorted(calls) if names.get(k[1], "").startswith(prefix)]
        if not group:
            continue
        lines += ["", f"## {title}", ""] + header
        lines += [row(k, calls[k]) for k in group]
    others = [k for k in sorted(calls) if not any(names.get(k[1], "").startswith(p) for p, _ in GROUPS)]
    if others:
        lines += ["", "## Others", ""] + header + [row(k, calls[k]) for k in others]
    lines += ["", f"Total: {len(calls)} routines called by the game, "
                  f"{sum(1 for k in routines if k[0] == 'I')} interrupts handled by the BIOS."]
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{out_path}: {len(calls)} routines, {sum(1 for k in routines if k[0] == 'I')} interrupts")
    return 0


if __name__ == "__main__":
    sys.exit(main())
