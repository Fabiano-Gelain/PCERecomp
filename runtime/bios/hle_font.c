static const Glyph *find_glyph(uint16_t code)
{
    for (size_t i = 0; i < sizeof(k_glyphs) / sizeof(k_glyphs[0]); i++)
        if (k_glyphs[i].code == code)
            return &k_glyphs[i];
    return NULL;
}

/* Drawing in 16 rows of 16 dots (bit 15 = left). In 16x16 the glyph sits in the middle, with the stroke
 * thickened by one dot to the right; in 12x12, starting at column 2. */
static void render(uint16_t code, int small, uint16_t rows[16])
{
    memset(rows, 0, 16 * sizeof(rows[0]));
    const Glyph *g = find_glyph(code);
    if (!g)
        return;
    int x0 = small ? 2 : 4, y0 = small ? 1 : 3;
    for (int r = 0; r < 11; r++) {
        const char *s = g->rows[r];
        uint16_t bits = 0;
        for (int c = 0; c < 7 && s[c]; c++)
            if (s[c] == '#')
                bits |= (uint16_t)(0x8000 >> (x0 + c));
        if (!small)
            bits |= (uint16_t)(bits >> 1);
        rows[y0 + r] = bits;
    }
}

int hle_font_render(uint16_t sjis, int small, uint16_t rows[16])
{
    render(sjis, small, rows);
    return find_glyph(sjis) != NULL;
}

/* Shift-JIS -> JIS row and column (as the BIOS validates the code). Returns 0 if it is not a character. */
static int sjis_to_jis(uint16_t code, uint8_t *row, uint8_t *col)
{
    int hi = (code >> 8) - 0x81;
    if (hi < 0 || hi >= 0x6F)
        return 0;
    if (hi >= 0x1F) {
        if (hi < 0x3F)
            return 0;
        hi -= 0x40;
    }
    int r = hi * 2 + 0x21;
    int lo = (code & 0xFF) - 0x40;
    if (lo < 0 || lo >= 0xBD || lo == 0x3F)
        return 0;
    if (lo < 0x3F)
        lo++;
    if (lo >= 0x5F) {
        r++;
        lo -= 0x3E;
    } else {
        lo += 0x20;
    }
    if (r >= 0x28 && (r < 0x30 || r >= 0x50))
        return 0;
    *row = (uint8_t)r;
    *col = (uint8_t)lo;
    return 1;
}

/* Timing (CPU cycles) of the BIOS conversion for the code `code` (F1FC, including the RTS): it branches
 * according to the JIS row and column */
static int convert_cycles(uint16_t code)
{
    uint8_t a = (uint8_t)((code >> 8) - 0x81);
    int t = 12; /* F1FC */
    if (a >= 0x6F)
        return t + 2 + 9; /* F22D */
    t += 4; /* F205 */
    if (a < 0x1F) {
        t += 2;
    } else {
        t += 4; /* F209 */
        if (a < 0x3F)
            return t + 2 + 9;
        t += 2; /* F20D */
        a = (uint8_t)(a - 0x40);
    }
    uint8_t row = (uint8_t)(a * 2 + 0x21);
    uint8_t lo = (uint8_t)((code & 0xFF) - 0x40);
    t += 20; /* F20F */
    if (lo >= 0xBD)
        return t + 2 + 9;
    t += 4; /* F21D */
    if (lo == 0x3F)
        return t + 2 + 9;
    t += 4 + 4; /* F221/F223, F224 */
    if (lo < 0x3F)
        lo++;
    if (lo >= 0x5F) {
        t += 2 + 10; /* F22F */
        row++;
        lo = (uint8_t)(lo - 0x3E);
    } else {
        t += 8; /* F228 */
        lo = (uint8_t)(lo + 0x20);
    }
    t += 12; /* F234 */
    if (row == 0x23)
        return t + 2 + 10 + 6 + 8 + 8 + 47; /* F255-F263, F27A, F27E */
    t += 4; /* F23C */
    if (row == 0x26)
        return t + 2 + (lo < 0x41 ? 10 : 14) + 8 + 47; /* F268, F26E, F27A, F27E */
    t += 4; /* F240 */
    if (row == 0x27)
        return t + 2 + 10 + 8 + 47; /* F272, F27A, F27E */
    t += 4; /* F244 */
    if (row < 0x28)
        return t + 2 + 47;
    t += 4; /* F248 */
    if (row < 0x30)
        return t + 2 + 9;
    t += 4; /* F24C */
    if (row >= 0x50)
        return t + 2 + 9;
    return t + 8 + 47; /* F250, F27E */
}

/* One iteration of the 12x12 copy (F2E6-F30C, 4 calls to F319): 4 extra cycles for each INC $FA that wraps */
static int small_loop_cycles(Pce *pce, int k)
{
    int t = 240;
    uint8_t fa = pce->hle->font_fa;
    for (int j = 0; j < 4; j++)
        if ((uint8_t)(fa + 4 * k + j + 1) == 0)
            t += 4;
    return t;
}

static void ex_getfnt(Pce *pce)
{
    uint16_t code = (uint16_t)(z(pce, 0xF8) | (z(pce, 0xF9) << 8));
    uint8_t row, col;
    if (!sjis_to_jis(code, &row, &col)) {
        A = alu_nz(pce, 0x01);
        alu_setc(pce, 1);
        hle_cycles(pce, 4 + 7 + convert_cycles(code) + 2 + 9); /* JMP, JSR F1FC, F140, F142 */
        hle_rts(pce);
        return;
    }
    /* BIOS temporary variables: here, the JIS row and column */
    zw(pce, 0xF8, col);
    zw(pce, 0xF9, row);
    zw(pce, 0xEC, 0);
    zw(pce, 0xED, 0);
    zw(pce, 0xEE, 0);
    int small = z(pce, 0xFF) & 0x01;
    /* The BIOS borrows two memory windows that don't cover the destination, and restores them at the end */
    int high = !((uint8_t)(z(pce, 0xFB) - 0xA0) & 0x80);
    zw(pce, 0xFC, high ? 0x60 : 0xA0);
    int w = high ? 3 : 5;
    mw(pce, (uint16_t)(0x22B8 + (high ? 0 : 2)), pce->cpu.mpr[w]);
    mw(pce, (uint16_t)(0x22B9 + (high ? 0 : 2)), pce->cpu.mpr[w + 1]);
    uint16_t rows[16];
    render(code, small, rows);
    uint16_t dest = (uint16_t)(z(pce, 0xFA) | (z(pce, 0xFB) << 8));
    for (int i = 0; i < 16; i++) {
        mw(pce, (uint16_t)(dest + 2 * i), (uint8_t)(rows[i] >> 8));
        mw(pce, (uint16_t)(dest + 2 * i + 1), (uint8_t)rows[i]);
    }
    if (small) {
        mw(pce, 0x22BD, 0);
        dest = (uint16_t)(dest + 24);
        zw(pce, 0xFA, (uint8_t)dest);
        zw(pce, 0xFB, (uint8_t)(dest >> 8));
    }
    /* The drawing is already at the destination; the rest is the timing of the BIOS copy loops, in steps (the
     * interrupts come in between them, as in the middle of the BIOS copy). */
    X = 0;
    Y = 0;
    pce->hle->font_fa = (uint8_t)(dest - (small ? 24 : 0));
    int cycles = 4 + 7 + convert_cycles(code) + 4 + 16 + (high ? 2 + 24 : 22) + 26; /* F140, F145, F15C/F150, F16A */
    cycles += small ? 2 + 8 * 40 + 7 * 2 + 22 : 2 + 2 + 5 * 22 + 4 * 2; /* F177-F18E or F196-F198 */
    cycles += 22 + 5 * 12 + 4 * 2 + 30 + (high ? 16 : 2 + 12); /* F1A1, F1AD, F1B3, F1C3/F1CA */
    cycles += small ? 6 + 2 + 7 + 2 : 6 + 2; /* F1CF, JSR F2E5, CLY or F1D2 */
    hle_cycles(pce, cycles);
    pce->cpu.pc = small ? 0xF2E6 : 0xF1D3;
}

/* End: windows restored (the last write by TAM stays in the TMA register), A = 0, C = 1 */
static void getfnt_end(Pce *pce, int high, int cycles)
{
    uint8_t last = m(pce, (uint16_t)(0x22B9 + (high ? 0 : 2)));
    pce->cpu.mpr_buffer = last;
    alu_nz(pce, last);
    alu_setc(pce, 1);
    A = 0;
    hle_cycles(pce, cycles + (high ? 6 + 24 : 8 + 20) + 9); /* F1E1, F1E4/F1F0, F1FA */
    hle_rts(pce);
}

/* F2E6: 12x12, 3 bytes of the font (2 rows) per iteration */
static void getfnt_small_step(Pce *pce)
{
    int t = small_loop_cycles(pce, Y / 3);
    Y = (uint8_t)(Y + 3);
    X = 0;
    if (Y < 0x12) {
        hle_cycles(pce, t + 2);
        pce->cpu.pc = 0xF2E6;
        return;
    }
    Y = 0xFF;
    getfnt_end(pce, z(pce, 0xFC) == 0x60, t + 4 + 102 + 7); /* F310, F313, RTS */
}

/* F1D3: 16x16, 4 bytes per step */
static void getfnt_big_step(Pce *pce)
{
    Y = (uint8_t)(Y + 4);
    if (Y < 0x20) {
        hle_cycles(pce, 88);
        pce->cpu.pc = 0xF1D3;
        return;
    }
    getfnt_end(pce, z(pce, 0xFC) == 0x60, 86 + 4); /* F1D3 (4 bytes), F1DC */
}

