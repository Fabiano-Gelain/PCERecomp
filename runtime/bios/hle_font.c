/*
 * C BIOS: ex_getfnt ($E060), which draws a Japanese character (Shift-JIS) from the console font.
 * See hle.h.
 *
 * The real BIOS stores 16x16 and 12x12 fonts (kanji and everything else); that data can't ship with the
 * program. This is a custom, hand-drawn font covering only the most common characters: "wide" letters, digits and
 * symbols (Shift-JIS $8140-$8197, $824F-$829A). Other valid characters come out blank.
 *
 * Input: $20F8/$20F9 the character (low / high byte of the Shift-JIS), ($20FA) destination, $20FF bit 0:
 * 0 = 16x16, 1 = 12x12. Output: 32 bytes at the destination, 2 per row (bit 7 of the 1st byte = leftmost
 * pixel); for 12x12 only the first 12 rows and 12 columns are used. A = 0 (ok, C = 1) or
 * A = 1 (C = 1) for a code that is not a character.
 */
